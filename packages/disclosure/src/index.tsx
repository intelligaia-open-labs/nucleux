import * as React from "react";
import { X } from "lucide-react";
import { cn } from "@nucleux/utils";
import { Button } from "@nucleux/button";
import { AiColorDot } from "@nucleux/color";
import { useAiGlyph } from "@nucleux/ai-icons";

/**
 * Presentation.
 * - `header-badge` — a small "AI" chip beside the agent name in a message header.
 * - `footer-attribution` — a caption under output: who generated it, what to do with it.
 * - `input-chip` — a persistent chip by the composer: "Chatting with Aria · AI assistant".
 * - `first-run-banner` — the heavier first-session notice, with a policy link; dismissible.
 * - `pill`, `badge`, `banner` — the original inline pill, corner badge and full-width banner (kept).
 */
export type DisclosureVariant =
  | "pill"
  | "badge"
  | "banner"
  | "header-badge"
  | "footer-attribution"
  | "input-chip"
  | "first-run-banner";

export interface DisclosureProps extends React.HTMLAttributes<HTMLDivElement> {
  /** Presentation. Default `pill`. */
  variant?: DisclosureVariant;
  /** Leading icon. Defaults to the reserved "generated with AI" mark from `@nucleux/ai-icons`. Pass `null` to omit. */
  icon?: React.ReactNode;
  /** Label / message. Ignored if `children` is provided. Has a per-variant default. */
  label?: React.ReactNode;
  /** The agent's name, used in the default copy ("Generated by Aria · verify before sharing."). */
  agentName?: string;
  /**
   * What the agent did, what it used and what nobody checked. When set on
   * `pill`, `badge`, `header-badge`, `input-chip` or `footer-attribution`,
   * the label becomes a toggle (`aria-expanded`) that opens these details in place.
   */
  details?: React.ReactNode;
  /** `first-run-banner`: the heading. Defaults to "You're chatting with <agent>, an AI assistant." */
  heading?: React.ReactNode;
  /** `first-run-banner` / `banner`: link to the full AI policy. */
  policyHref?: string;
  /** Text of the policy link. Default "Read policy". */
  policyLabel?: React.ReactNode;
  /**
   * `first-run-banner` / `banner`: show a Dismiss button. Called after the
   * banner hides itself — persist it so the banner is shown once per user.
   */
  onDismiss?: () => void;
  /** Accessible name of the dismiss button. Default "Dismiss". */
  dismissLabel?: string;
}

function defaultCopy(variant: DisclosureVariant, agent?: string): React.ReactNode {
  switch (variant) {
    case "pill":
      return "AI-assisted";
    case "badge":
      return "Made with AI";
    case "banner":
      return "This content was generated by AI. Review it before relying on it.";
    case "header-badge":
      return "AI";
    case "footer-attribution":
      return `Generated by ${agent ?? "AI"} · verify before sharing.`;
    case "input-chip":
      return agent ? `Chatting with ${agent} · AI assistant` : "Chatting with an AI assistant";
    case "first-run-banner":
      return `${agent ?? "The assistant"} can summarise, draft and search. Responses are generated — not authored by a person — and may contain mistakes.`;
  }
}

const chipClasses: Partial<Record<DisclosureVariant, string>> = {
  pill: "gap-1 rounded-full bg-brand-muted/60 px-2.5 py-1 text-xs font-medium text-foreground [&_svg]:size-3.5 [&_svg]:text-brand",
  badge:
    "gap-1 rounded-full bg-background/90 px-2 py-1 text-xs font-medium text-foreground shadow-sm backdrop-blur [&_svg]:size-3.5 [&_svg]:text-brand",
  "header-badge":
    "gap-1 rounded bg-primary px-1.5 py-0.5 text-[10px] font-semibold uppercase leading-none tracking-wider text-primary-foreground [&_svg]:size-2.5",
  "input-chip":
    "gap-1.5 rounded-full border border-brand/40 bg-brand-muted px-2.5 py-0.5 text-xs font-semibold text-foreground",
  "footer-attribution": "gap-1.5 text-xs text-muted-foreground [&_svg]:size-3",
};

const AiChipMark = () => (
  <span
    aria-hidden="true"
    className="rounded bg-primary px-1.5 py-0.5 text-[10px] font-semibold uppercase leading-none tracking-wider text-primary-foreground"
  >
    AI
  </span>
);

/**
 * A clear, visible label that tells people they are dealing with an AI, not
 * a person, and marks content the AI generated — at the point it matters.
 * Variants: `header-badge`, `footer-attribution`, `input-chip`,
 * `first-run-banner` (plus the original `pill`, `badge`, `banner`). It
 * draws the same reserved marks as `@nucleux/ai-icons`, and with `details`
 * the label opens in place to say what the agent did and what nobody checked.
 */
export const Disclosure = React.forwardRef<HTMLDivElement, DisclosureProps>(
  (
    {
      variant = "pill",
      icon,
      label,
      agentName,
      details,
      heading,
      policyHref,
      policyLabel = "Read policy",
      onDismiss,
      dismissLabel = "Dismiss",
      className,
      children,
      ...props
    },
    ref,
  ) => {
    const GeneratedGlyph = useAiGlyph("generated-content");
    const [dismissed, setDismissed] = React.useState(false);
    const [open, setOpen] = React.useState(false);
    const detailsId = React.useId();
    const content = children ?? label ?? defaultCopy(variant, agentName);

    if (dismissed) return null;

    const dismissButton = onDismiss ? (
      <Button
        variant="ghost"
        size="icon-sm"
        aria-label={dismissLabel}
        className="-my-1 ml-auto shrink-0 [&_svg]:size-4"
        onClick={() => {
          setDismissed(true);
          onDismiss();
        }}
      >
        <X aria-hidden="true" />
      </Button>
    ) : null;

    const policyLink = policyHref ? (
      <a
        href={policyHref}
        className="ml-1 font-medium text-foreground underline underline-offset-2 hover:opacity-80 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
      >
        {policyLabel}
      </a>
    ) : null;

    if (variant === "first-run-banner") {
      return (
        <div
          ref={ref}
          data-variant={variant}
          className={cn(
            "rounded-lg border border-border border-l-[3px] border-l-brand bg-brand-muted/50 px-4 py-3.5",
            className,
          )}
          {...props}
        >
          <div className="flex items-center gap-2 text-sm font-semibold text-foreground">
            <AiChipMark />
            <span>{heading ?? `You're chatting with ${agentName ?? "an AI assistant"}${agentName ? ", an AI assistant" : ""}.`}</span>
            {dismissButton}
          </div>
          <p className="mt-1.5 text-xs leading-relaxed text-muted-foreground">
            {content}
            {policyLink}
          </p>
        </div>
      );
    }

    const glyph = icon === undefined ? <GeneratedGlyph /> : icon;

    if (variant === "banner") {
      return (
        <div
          ref={ref}
          data-variant={variant}
          className={cn(
            "flex items-center gap-2 rounded-lg border border-brand/20 bg-brand-muted/40 px-3 py-2 text-sm text-foreground [&_svg]:size-4 [&_svg]:text-brand",
            className,
          )}
          {...props}
        >
          {glyph}
          <span>
            {content}
            {policyLink}
          </span>
          {dismissButton}
        </div>
      );
    }

    // Chip-like variants.
    const chipGlyph = variant === "header-badge" || variant === "input-chip" ? null : glyph;
    const leading =
      variant === "input-chip" ? <AiColorDot /> : variant === "header-badge" && icon ? icon : chipGlyph;
    const chipBody = (
      <>
        {leading}
        <span>{content}</span>
      </>
    );
    const chip = chipClasses[variant] ?? chipClasses.pill;
    const wrapper =
      variant === "footer-attribution" ? "mt-2.5 flex border-t border-border pt-2.5" : "inline-flex w-fit";

    if (details == null) {
      return (
        <div
          ref={ref}
          data-variant={variant}
          className={cn(wrapper, "items-center", chip, className)}
          {...props}
        >
          {chipBody}
        </div>
      );
    }

    return (
      <div
        ref={ref}
        data-variant={variant}
        className={cn(wrapper, "flex-col items-start gap-1.5", className)}
        {...props}
      >
        <button
          type="button"
          aria-expanded={open}
          aria-controls={detailsId}
          onClick={() => setOpen((o) => !o)}
          className={cn(
            "inline-flex items-center focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-1",
            chip,
            variant === "footer-attribution" && "rounded-sm hover:text-foreground",
          )}
        >
          {chipBody}
        </button>
        <div
          id={detailsId}
          hidden={!open}
          className="w-full rounded-md border border-border bg-background p-3 text-xs leading-relaxed text-foreground"
        >
          {details}
        </div>
      </div>
    );
  },
);
Disclosure.displayName = "Disclosure";
