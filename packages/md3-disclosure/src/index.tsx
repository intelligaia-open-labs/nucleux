import * as React from "react";
import { X } from "lucide-react";
import { cn } from "@nucleux/utils";
import type { DisclosureProps, DisclosureVariant } from "@nucleux/disclosure";
import { useAiGlyph } from "@nucleux/md3-ai-icons";
import { Md3AiColorDot } from "@nucleux/md3-color";
import { Md3Card } from "@nucleux/md3-card";
import { Md3IconButton } from "@nucleux/md3-icon-button";

export type Md3DisclosureProps = DisclosureProps;
export type Md3DisclosureVariant = DisclosureVariant;

// Copied from @nucleux/disclosure (internal there) so both families say the same words.
function defaultCopy(variant: DisclosureVariant, agent?: string): React.ReactNode {
  switch (variant) {
    case "pill":
      return "AI-assisted";
    case "badge":
      return "Made with AI";
    case "banner":
      return "This content was generated by AI. Review it before relying on it.";
    case "header-badge":
      return "AI";
    case "footer-attribution":
      return `Generated by ${agent ?? "AI"} · verify before sharing.`;
    case "input-chip":
      return agent ? `Chatting with ${agent} · AI assistant` : "Chatting with an AI assistant";
    case "first-run-banner":
      return `${agent ?? "The assistant"} can summarise, draft and search. Responses are generated — not authored by a person — and may contain mistakes.`;
  }
}

const stateLayer =
  "relative overflow-hidden before:absolute before:inset-0 before:bg-current before:opacity-0 before:transition-opacity before:content-[''] hover:before:opacity-[0.08] focus-visible:before:opacity-[0.12] active:before:opacity-[0.12] motion-reduce:before:transition-none [&>svg]:relative";

// M3 assist chips. The disclosure chip's role is secondary-container.
const chipClasses: Partial<Record<DisclosureVariant, string>> = {
  pill: "h-6 gap-1 rounded-md-sm bg-md-secondary-container px-2 text-xs font-medium tracking-[0.5px] text-md-on-secondary-container [&_svg]:size-3.5",
  badge:
    "h-6 gap-1 rounded-md-sm bg-md-surface-container-low px-2 text-xs font-medium tracking-[0.5px] text-md-on-surface shadow-md-1 [&_svg]:size-3.5 [&_svg]:text-md-primary",
  "header-badge":
    "gap-1 rounded-md-xs bg-md-secondary-container px-1.5 py-0.5 text-[11px] font-medium uppercase leading-4 tracking-[0.5px] text-md-on-secondary-container [&_svg]:size-3",
  "input-chip":
    "h-8 gap-2 rounded-md-sm border border-md-outline-variant bg-md-surface px-3 text-sm font-medium tracking-[0.1px] text-md-on-surface",
  "footer-attribution": "gap-1.5 text-xs tracking-[0.4px] text-md-on-surface-variant [&_svg]:size-3.5 [&_svg]:text-md-primary",
};

const AiChipMark = () => (
  <span
    aria-hidden="true"
    className="rounded-md-xs bg-md-on-tertiary-container px-1.5 py-0.5 text-[11px] font-medium uppercase leading-4 tracking-[0.5px] text-md-tertiary-container"
  >
    AI
  </span>
);

/**
 * A clear label that tells people they are dealing with an AI, and marks
 * what it produced, at the point it matters — the Material 3 twin of
 * `Disclosure`, with the same API. The chip variants are M3 assist chips on
 * the secondary-container disclosure role; `banner` and `first-run-banner`
 * are standing notices on the tertiary container; `footer-attribution` is a
 * caption under a divider. With `details`, the label becomes a state-layer
 * toggle that grows an outlined Md3Card in place saying what the agent did,
 * what it used and what nobody checked. The marks are the shared reserved
 * glyphs from `@nucleux/md3-ai-icons`.
 */
export const Md3Disclosure = React.forwardRef<HTMLDivElement, Md3DisclosureProps>(
  (
    {
      variant = "pill",
      icon,
      label,
      agentName,
      details,
      heading,
      policyHref,
      policyLabel = "Read policy",
      onDismiss,
      dismissLabel = "Dismiss",
      className,
      children,
      ...props
    },
    ref,
  ) => {
    const GeneratedGlyph = useAiGlyph("generated-content");
    const [dismissed, setDismissed] = React.useState(false);
    const [open, setOpen] = React.useState(false);
    const detailsId = React.useId();
    const content = children ?? label ?? defaultCopy(variant, agentName);

    if (dismissed) return null;

    const dismissButton = onDismiss ? (
      <Md3IconButton
        aria-label={dismissLabel}
        className="-my-2 ml-auto size-8 shrink-0 text-md-on-tertiary-container [&_svg]:size-5"
        onClick={() => {
          setDismissed(true);
          onDismiss();
        }}
      >
        <X aria-hidden="true" />
      </Md3IconButton>
    ) : null;

    const policyLink = policyHref ? (
      <a
        href={policyHref}
        className="ml-1 rounded-md-xs font-medium text-md-on-tertiary-container underline underline-offset-2 outline-none hover:opacity-80 focus-visible:ring-2 focus-visible:ring-md-primary"
      >
        {policyLabel}
      </a>
    ) : null;

    if (variant === "first-run-banner") {
      return (
        <div
          ref={ref}
          data-variant={variant}
          className={cn(
            "font-md",
            "rounded-md-lg bg-md-tertiary-container px-4 py-3.5 text-md-on-tertiary-container animate-nx-fade-in motion-reduce:animate-none",
            className,
          )}
          {...props}
        >
          <div className="flex items-center gap-2 text-sm font-medium tracking-[0.1px]">
            <AiChipMark />
            <span>
              {heading ??
                `You're chatting with ${agentName ?? "an AI assistant"}${agentName ? ", an AI assistant" : ""}.`}
            </span>
            {dismissButton}
          </div>
          <p className="mt-1.5 text-xs leading-5 tracking-[0.4px]">
            {content}
            {policyLink}
          </p>
        </div>
      );
    }

    const glyph = icon === undefined ? <GeneratedGlyph /> : icon;

    if (variant === "banner") {
      return (
        <div
          ref={ref}
          data-variant={variant}
          className={cn(
            "font-md",
            "flex items-center gap-4 rounded-md-md bg-md-tertiary-container py-3 pl-4 pr-3 text-sm text-md-on-tertiary-container [&_svg]:size-5",
            className,
          )}
          {...props}
        >
          {glyph}
          <span>
            {content}
            {policyLink}
          </span>
          {dismissButton}
        </div>
      );
    }

    // Chip-like variants.
    const chipGlyph = variant === "header-badge" || variant === "input-chip" ? null : glyph;
    const leading =
      variant === "input-chip" ? <Md3AiColorDot /> : variant === "header-badge" && icon ? icon : chipGlyph;
    const chipBody = (
      <>
        {leading}
        <span className="relative">{content}</span>
      </>
    );
    const chip = chipClasses[variant] ?? chipClasses.pill;
    const wrapper =
      variant === "footer-attribution"
        ? "mt-2.5 flex border-t border-md-outline-variant pt-2.5"
        : "inline-flex w-fit";

    if (details == null) {
      return (
        <div ref={ref} data-variant={variant} className={cn("font-md", wrapper, "items-center", chip, className)} {...props}>
          {chipBody}
        </div>
      );
    }

    return (
      <div ref={ref} data-variant={variant} className={cn("font-md", wrapper, "flex-col items-start gap-2", className)} {...props}>
        <button
          type="button"
          aria-expanded={open}
          aria-controls={detailsId}
          onClick={() => setOpen((o) => !o)}
          className={cn(
            "inline-flex items-center outline-none focus-visible:ring-2 focus-visible:ring-md-primary",
            chip,
            stateLayer,
            variant === "footer-attribution" && "-mx-1 rounded-md-xs px-1 hover:text-md-on-surface",
          )}
        >
          {chipBody}
        </button>
        <Md3Card
          id={detailsId}
          variant="outlined"
          hidden={!open}
          className="w-full rounded-md-md p-3 text-xs leading-5 animate-nx-fade-in motion-reduce:animate-none"
        >
          {details}
        </Md3Card>
      </div>
    );
  },
);
Md3Disclosure.displayName = "Md3Disclosure";
